#!/usr/bin/env node
/**
 * build-archive-links.js
 *
 * Injects a STATIC, crawlable index of every article into the two hub pages
 * (the-leaf/index.html + field-guide/index.html). The hubs render their card
 * grids with JavaScript (fetch manifest.json → innerHTML), so Googlebot's raw
 * crawl of the hub sees ZERO article links and never passes crawl-equity to the
 * articles — which is why most of /the-leaf/ sat "Discovered, not indexed".
 *
 * This adds a plain <a href> list (grouped by category) the raw HTML crawler
 * follows, making every article one static hop from a crawled hub. The visible
 * JS grid is untouched; this sits below it as a "Browse everything" archive.
 *
 * Idempotent: re-run after adding articles (regenerates between the markers).
 *   node pipeline/build-archive-links.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const feed = JSON.parse(fs.readFileSync(path.join(ROOT, "feed.json"), "utf8"));
const items = Array.isArray(feed) ? feed : (feed.articles || feed.items);

const START = "<!-- archive-index:start (generated by pipeline/build-archive-links.js — do not edit by hand) -->";
const END = "<!-- archive-index:end -->";

const HUBS = [
  { section: "the-leaf", file: "the-leaf/index.html", label: "the Understory" },
  { section: "field-guide", file: "field-guide/index.html", label: "the Field Guide" },
];

function esc(s) {
  return String(s || "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function path4(url) {
  // Store root-relative hrefs so they're stable regardless of host.
  try { return new URL(url).pathname; } catch { return url; }
}

function buildSection(sectionItems, label) {
  // Group by category, alpha within, categories alpha.
  const byCat = {};
  for (const it of sectionItems) {
    const cat = (it.category || "More").trim();
    (byCat[cat] = byCat[cat] || []).push(it);
  }
  const cats = Object.keys(byCat).sort((a, b) => a.localeCompare(b));
  let inner = "";
  for (const cat of cats) {
    const links = byCat[cat]
      .sort((a, b) => (a.title || "").localeCompare(b.title || ""))
      .map((it) => `      <li><a href="${esc(path4(it.url))}">${esc(it.title)}</a></li>`)
      .join("\n");
    inner += `    <div class="archive-cat">\n      <h3 class="archive-cat-label">${esc(cat)}</h3>\n      <ul class="archive-list">\n${links}\n      </ul>\n    </div>\n`;
  }
  const style = `  <style>
    .archive-index{max-width:1100px;margin:4rem auto 0;padding:2.5rem 2rem 0;border-top:1px solid var(--border,rgba(255,255,255,.08));}
    .archive-heading{font-size:1rem;letter-spacing:.02em;color:var(--text-faint,rgba(255,255,255,.55));font-weight:600;margin:0 0 1.5rem;text-transform:uppercase;}
    .archive-cols{columns:3;column-gap:2.5rem;}
    .archive-cat{break-inside:avoid;margin:0 0 1.5rem;}
    .archive-cat-label{font-size:.82rem;color:var(--text-faint,rgba(255,255,255,.5));margin:0 0 .5rem;font-weight:600;}
    .archive-list{list-style:none;margin:0;padding:0;}
    .archive-list li{margin:0 0 .35rem;}
    .archive-list a{color:var(--text-dim,rgba(255,255,255,.7));text-decoration:none;font-size:.9rem;line-height:1.35;}
    .archive-list a:hover{color:var(--accent,#5BD17A);text-decoration:underline;}
    @media(max-width:820px){.archive-cols{columns:2;}}
    @media(max-width:520px){.archive-cols{columns:1;}}
  </style>`;
  return [
    START,
    `<section class="archive-index" aria-label="All articles in ${esc(label)}">`,
    style,
    `  <h2 class="archive-heading">Browse everything in ${esc(label)}</h2>`,
    `  <div class="archive-cols">`,
    inner.trimEnd(),
    `  </div>`,
    `</section>`,
    END,
  ].join("\n");
}

let total = 0;
for (const hub of HUBS) {
  const file = path.join(ROOT, hub.file);
  let html = fs.readFileSync(file, "utf8");
  const sectionItems = items.filter((i) => i.section === hub.section);
  const block = buildSection(sectionItems, hub.label);

  const re = new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  if (re.test(html)) {
    html = html.replace(re, block);
  } else {
    // Insert just before </main> (falls back to before <footer).
    if (html.includes("</main>")) html = html.replace("</main>", `${block}\n</main>`);
    else html = html.replace(/<footer/, `${block}\n<footer`);
  }
  fs.writeFileSync(file, html);
  console.log(`✓ ${hub.file}: ${sectionItems.length} ${hub.section} links injected`);
  total += sectionItems.length;
}
console.log(`Done — ${total} static article links across ${HUBS.length} hubs.`);
